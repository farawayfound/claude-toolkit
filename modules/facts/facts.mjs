// facts.mjs: renders the repo-facts block for CLAUDE.local.md from detect.mjs. Reads files only.
// Module: import { renderFacts } from './facts.mjs'.  CLI: node facts.mjs [root]  (prints the block)
import fs from 'node:fs';
import path from 'node:path';
import { detect } from './detect.mjs';

export function renderFacts(root, det = detect(root)) {
  const L = ['Generated by dev-toolkit from repo files; add your own notes below the end marker.', '',
    `Stack: ${det.stacks.join(', ') || 'not detected'}${det.pm ? `; package manager: ${det.pm}` : ''}.`, ''];
  const rows = Object.entries(det.commands).flatMap(([k, list]) => list.map((c) => `| ${k} | \`${c.cmd}\` | ${c.source} |`));
  if (rows.length) L.push('| Purpose | Command | Source |', '|---|---|---|', ...rows, '');
  else L.push('No test, lint or format command detected: read the README and CI first.', '');
  L.push(det.ci.length ? `Confirm commands against CI: ${det.ci.join(', ')}` : 'No CI workflow found: treat every command above as unverified.');
  if (det.services.length) L.push(`Services: ${det.services.join(', ')}; tests may need \`docker compose up -d <service>\`; ask before starting containers.`);
  if (det.envExample) L.push('.env.example lists required keys; never open .env.');
  if (det.pythonEnv === 'none') L.push('Python env not set up: ask first, then `uv sync` (creates .venv and uv.lock) or `uv venv && uv pip install -r requirements*.txt`; keep an untracked uv.lock out of the PR.');
  if (det.conventions.length) L.push(`Read first: ${det.conventions.join(', ')}`);
  if (det.subprojects.length) L.push(`Nested packages (their commands above run from this root; \`cd <dir> && ...\` forms are not allow-listed): ${det.subprojects.join(', ')}`);
  if (fs.existsSync(path.join(root, 'AGENTS.md'))) L.push('@AGENTS.md');
  return L.join('\n');
}

if (/facts\.mjs$/.test(process.argv[1] || '')) console.log(renderFacts(path.resolve(process.argv[2] || process.cwd())));
